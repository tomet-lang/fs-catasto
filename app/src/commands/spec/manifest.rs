//! Manifest reference generator from catasto-manifest schema definitions.

use tomet_spec::PrinterConfig;

const DOC_ID: &str = "doc-manifestDocRf";
const TITLE: &str = "Manifest Reference";
const NOTICE: &str = "Generated by `catasto spec manifest` from Rust schema definitions in \
     `crates/catasto-manifest/`. Do not edit it: change the doc comments there and run \
     the command again.";
const INTRO: &str =
    "Authoritative reference of all declarations and fields supported in `catasto.ctmt`.";

/// Renders the complete formatted manifest specification `.tmt` string.
pub fn render(config: &PrinterConfig) -> String {
    let specs = catasto_manifest::all_manifest_specs();
    tomet_spec::config::render(&specs, DOC_ID, TITLE, &[NOTICE, INTRO], config)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rendered() -> String {
        render(&PrinterConfig::default())
    }

    #[test]
    fn manifest_spec_is_valid_tmt() {
        let text = rendered();
        tomet_parser::parse_document(&text).expect("generated manifest spec parses as valid tmt");
        assert!(text.contains("==[ upstreams ]") || text.contains("==[upstreams]"));
        assert!(text.contains("==[ entry ]") || text.contains("==[entry]"));
        assert!(text.contains("`source`"));
        assert!(text.contains("`git`"));
    }

    #[test]
    fn manifest_spec_is_deterministic() {
        assert_eq!(rendered(), rendered());
    }
}
