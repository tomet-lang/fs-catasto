//! CLI command reference generator from clap definitions.

use clap::CommandFactory;
use tomet_spec::PrinterConfig;

use crate::cli::Cli;

const DOC_ID: &str = "doc-cliDocRf";
const NOTICE: &str = "Generated by `catasto spec cli` from the clap definitions in \
     `app/src/cli.rs`. Do not edit it: change the doc comments there and run \
     the command again.";

/// Renders the complete formatted CLI specification `.tmt` string.
pub fn render(config: &PrinterConfig) -> String {
    let mut root = Cli::command();
    tomet_spec::cli::render(&mut root, DOC_ID, NOTICE, config)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rendered() -> String {
        render(&PrinterConfig::default())
    }

    #[test]
    fn every_subcommand_is_in_the_reference() {
        let text = rendered();
        let mut root = Cli::command();
        root.build();
        for sub in root.get_subcommands().filter(|s| s.get_name() != "help") {
            assert!(
                text.contains(&format!("catasto {}", sub.get_name())),
                "missing section for `catasto {}`",
                sub.get_name()
            );
        }
    }

    #[test]
    fn cli_spec_is_valid_tmt() {
        let text = rendered();
        tomet_parser::parse_document(&text).expect("generated cli spec parses as valid tmt");
    }

    #[test]
    fn cli_spec_is_deterministic() {
        assert_eq!(rendered(), rendered());
    }
}
